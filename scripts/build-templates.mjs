// Turns the text of the Dev templates into carve strokes (single-line Hershey font).
// Usage: pnpm build:templates   (writes src/lib/carve/templates.generated.ts, then formats it)
//
// Font data stays here: only the generated strokes ship to the runtime.
// Source: Hershey Simplex ("Sans 1-stroke", `futural`) from the `hersheytext` JSON port
// (npm hersheytext@1.0.0, MIT, https://unpkg.com/hersheytext@1.0.0/hersheytext.min.json),
// subset to the glyphs used below. The Hershey Fonts were originally created by
// Dr. A. V. Hershey at the U. S. National Bureau of Standards.
// Glyph space: y grows down, baseline y = 22, cap top y = 1; `M` starts a new stroke (pen lift).
import fs from 'node:fs';

const OUT = process.argv[2] ?? './src/lib/carve/templates.generated.ts';

const GLYPHS = {
  ':': 'M4,10 L3,11 4,12 5,11 4,10 M4,17 L3,18 4,19 5,18 4,17',
  N: 'M4,1 L4,22 M4,1 L18,22 M18,1 L18,22',
  a: 'M15,8 L15,22 M15,11 L13,9 11,8 8,8 6,9 4,11 3,14 3,16 4,19 6,21 8,22 11,22 13,21 15,19',
  w: 'M3,8 L7,22 M11,8 L7,22 M11,8 L15,22 M19,8 L15,22',
  q: 'M15,8 L15,29 M15,11 L13,9 11,8 8,8 6,9 4,11 3,14 3,16 4,19 6,21 8,22 11,22 13,21 15,19',
  0: 'M9,1 L6,2 4,5 3,10 3,13 4,18 6,21 9,22 11,22 14,21 16,18 17,13 17,10 16,5 14,2 11,1 9,1',
  1: 'M6,5 L8,4 11,1 11,22',
  _: 'M0,29 L18,29',
  '>': 'M4,4 L20,13 4,22',
  '<': 'M20,4 L4,13 20,22',
  '^': 'M8,-1 L0,13 M8,-1 L16,13',
};

const CAP_HEIGHT = 21; // y = 1..22
const MID_Y = 11.5;
const GLYPH_GAP = 6;
const SPACE_ADVANCE = 12;
const STROKE_W = 0.04;
const AREA_MIN = 0.2; // templates must stay inside the face area (see templates.test.ts)
const AREA_MAX = 0.8;
const MAX_LINE_WIDTH = 0.5;

// cy / height are in UV; `height` is the cap height.
const TEMPLATES = {
  nan: [{ text: 'NaN', cy: 0.5, height: 0.2 }],
  wq: [{ text: ':wq', cy: 0.5, height: 0.2 }],
  binary: [
    { text: '0 1', cy: 0.62, height: 0.16 },
    { text: '_', cy: 0.52, height: 0.16 },
  ],
  'kaomoji-angry': [{ text: '>_<', cy: 0.5, height: 0.2 }],
  'kaomoji-happy': [{ text: '^_^', cy: 0.5, height: 0.2 }],
};

const round3 = (n) => Math.round(n * 1000) / 1000;

// "M4,8 L4,22 M..." → [[[4, 8], [4, 22]], ...]
const parseGlyph = (path) =>
  path
    .split('M')
    .filter((chunk) => chunk.trim() !== '')
    .map((chunk) =>
      chunk
        .replace(/L/g, ' ')
        .trim()
        .split(/\s+/)
        .map((pair) => pair.split(',').map(Number)),
    );

const glyphFor = (char) => {
  const path = GLYPHS[char];
  if (path === undefined) throw new Error(`No glyph for "${char}"`);
  return parseGlyph(path);
};

const minMaxX = (strokes) => {
  const xs = strokes.flat().map(([x]) => x);
  return [Math.min(...xs), Math.max(...xs)];
};

// Lays the glyphs out left to right in glyph units; returns strokes and total width.
const layoutLine = (text) => {
  const placed = [];
  let cursor = 0;
  [...text].forEach((char) => {
    if (char === ' ') {
      cursor += SPACE_ADVANCE;
      return;
    }
    const strokes = glyphFor(char);
    const [minX, maxX] = minMaxX(strokes);
    strokes.forEach((s) =>
      placed.push(s.map(([x, y]) => [x - minX + cursor, y])),
    );
    cursor += maxX - minX + GLYPH_GAP;
  });
  return { strokes: placed, width: cursor - GLYPH_GAP };
};

const lineToStrokes = ({ text, cy, height }) => {
  const { strokes, width } = layoutLine(text);
  const scale = Math.min(height / CAP_HEIGHT, MAX_LINE_WIDTH / width);
  const left = 0.5 - (width * scale) / 2; // centered on u = 0.5
  return strokes.map((pts) => ({
    w: STROKE_W,
    pts: pts.map(([x, y]) => [
      round3(left + x * scale),
      round3(cy - (y - MID_Y) * scale), // glyph y goes down, UV v goes up
    ]),
  }));
};

const assertInsideArea = (id, strokes) =>
  strokes.forEach(({ pts }) =>
    pts.forEach(([u, v]) => {
      if (u < AREA_MIN || u > AREA_MAX || v < AREA_MIN || v > AREA_MAX)
        throw new Error(`${id}: point [${u}, ${v}] is outside the face area`);
    }),
  );

const buildAll = () =>
  Object.fromEntries(
    Object.entries(TEMPLATES).map(([id, lines]) => {
      const strokes = lines.flatMap(lineToStrokes);
      assertInsideArea(id, strokes);
      return [id, strokes];
    }),
  );

const render = (all) =>
  [
    '// Generated by scripts/build-templates.mjs. Do not edit by hand.',
    "import type { Stroke } from './strokes';",
    '',
    `export const GENERATED_STROKES = ${JSON.stringify(all)} satisfies Record<string, Stroke[]>;`,
    '',
  ].join('\n');

fs.writeFileSync(OUT, render(buildAll()));
console.log(`wrote ${OUT}`);
